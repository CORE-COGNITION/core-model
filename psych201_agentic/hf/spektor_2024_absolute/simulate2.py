class TwoSessionChoice:
    """Experiment 3 (LAC vs GSC across two sessions ~1 week apart, two 180-trial
    blocks per session) of Spektor, Kellen, Rieskamp, & Klauer (2024), JEP:
    General.

    Design (Method, Exp. 3 / preregistered): each condition was comprised of 180
    unique trials (42 pure-gain, 42 pure-loss, 96 mixed) that were repeated in a
    newly randomized order once in every experimental session (two sessions,
    task_id 0/1, about a week apart; two 180-trial blocks per session). The 180
    lottery pairs per condition (with their source `gamble` ids) are taken verbatim
    from the repo's exp2.csv.
    Starting context is counterbalanced (order = 'GSC'/'LAC' start).

    The DataFrame matches exp2.csv minus the timing/click columns (rt, cclk,
    fchrt, chrt, okrt), the raw session/block dups (Session, Block), the variance
    estimates (var_X, var_Y) and the display-side columns (X1, X2, Y1, Y2, ur,
    dr, ul, dl, liste, right_risky), which a text simulator cannot reproduce.
    """

    def __init__(self):
        self.name = "spektor_2024_absolute_exp2"
        self.trials_per_block = 180
        self.blocks_per_session = 2
        self.sessions = 2

    def simulate(self, agent, num_simulations, max_chars=None):
        rows, prompts = [], []
        for pid in range(num_simulations):
            x_tok, y_tok = _token_map(pid)
            order = "GSC" if np.random.rand() < 0.5 else "LAC"
            cond_of_session = (["gain_seeking", "loss_aversion"] if order == "GSC"
                               else ["loss_aversion", "gain_seeking"])
            start_condition = 1 if order == "GSC" else 0
            lines = [_instructions(x_tok, y_tok)]
            for sess in range(self.sessions):
                if max_chars is not None and len("\n".join(lines)) >= max_chars:
                    break
                cond = cond_of_session[sess]
                for blk in range(self.blocks_per_session):
                    if max_chars is not None and len("\n".join(lines)) >= max_chars:
                        break
                    pool = list(POOLS[cond].items())
                    np.random.shuffle(pool)
                    if sess == 0 and blk == 0:
                        lines.append(f"Session {sess + 1} begins.")
                    elif sess > 0 and blk == 0:
                        lines.append(f"Session {sess + 1} begins (about a week later).")
                    else:
                        lines.append("New block.")
                    for g, (tdef, (gid, x1, x2, y1, y2, xvar, yvar, td1, td2)) in enumerate(pool, start=1):
                        prefix = (f"X: {_fmt(x1, x2)}. Y: {_fmt(y1, y2)}. "
                                  "You press [HUMAN_RESPONSE]")
                        prompt = "\n".join(lines) + "\n" + prefix
                        letter = agent(prompt, choice_options=[x_tok, y_tok])
                        response = 0 if letter == x_tok else 1
                        riskier = (xvar > yvar) if response == 0 else (yvar > xvar)
                        lines.append(prefix + f"{letter}[/HUMAN_RESPONSE].")
                        rows.append({
                            "participant_id": pid,
                            "trial": (blk * self.trials_per_block) + g - 1,
                            "response": response, "task_id": sess, "condition": cond,
                            "valid": 1, "block": blk, "gamble": gid,
                            "order": order, "trialWithinBlocks": g,
                            "rsp": "X" if response == 0 else "Y",
                            "start_condition": start_condition,
                            "rsp_risky": 1 if riskier else 0,
                            "Xvar": xvar, "Yvar": yvar,
                            "Xout1": x1, "Xout2": x2, "Yout1": y1, "Yout2": y2,
                            "trial_definition_1": td1, "trial_definition_2": td2,
                            "trial_definition": tdef,
                        })
            prompts.append("\n".join(lines).strip())
        df = pd.DataFrame(rows, columns=[
            "participant_id", "trial", "response", "task_id", "condition", "valid",
            "block", "gamble", "order", "trialWithinBlocks", "rsp",
            "start_condition", "rsp_risky", "Xvar", "Yvar", "Xout1", "Xout2",
            "Yout1", "Yout2", "trial_definition_1", "trial_definition_2",
            "trial_definition",
        ])
        return df, prompts


def _random_agent(prompt, choice_options):
    return str(np.random.choice(choice_options))


def main():
    parser = argparse.ArgumentParser(
        description="Smoke-test this simulator with a uniform-random agent.")
    parser.add_argument("-n", "--num-simulations", type=int, default=3, help="number of simulated participants (default: 3)")
    parser.add_argument("--max-chars", type=int, default=None, help="stop each participant at the block/session boundary at/past this many chars")
    parser.add_argument("--seed", type=int, default=None, help="numpy random seed, for reproducible runs")
    args = parser.parse_args()

    if args.seed is not None:
        np.random.seed(args.seed)

    task = TwoSessionChoice()
    df, prompts = task.simulate(_random_agent, args.num_simulations,
                                max_chars=args.max_chars)

    print(f"name: {task.name}")
    print(f"df shape: {df.shape}")
    print("dtypes:")
    print(df.dtypes.to_string())
    print("head:")
    print(df.head(8).to_string())
    print(f"prompt lengths: {[len(p) for p in prompts]}")
    for i, p in enumerate(prompts):
        first = p.splitlines()[0]
        if len(first) > 180:
            first = first[:90] + " … " + first[-90:]
        print(f"participant {i} first line: {first}")
    print("=" * 78)
    print("first prompt, head:")
    print(prompts[0][:600])
    print("...")
    print("first prompt, tail:")
    print(prompts[0][-300:])


if __name__ == "__main__":
    main()
